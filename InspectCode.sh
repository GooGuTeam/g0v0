#!/usr/bin/env bash
(set -o igncr) 2>/dev/null && set -o igncr # Handle CRLF on Windows with core.autocrlf=true

set -euo pipefail

REPO_ROOT="$(git rev-parse --show-toplevel)"
cd "$REPO_ROOT"

if [[ "${1:-}" == "--full" ]]; then
    chmod +x CheckSanity.sh
    dotnet tool restore
    dotnet clean ./osu.Desktop.slnf --verbosity=q
    dotnet build -c Debug -warnaserror osu.Desktop.slnf -p:EnforceCodeStyleInBuild=true
    ./CheckSanity.sh
    dotnet jb inspectcode "osu.Desktop.slnf" --no-build --format=Text --stdout --caches-home="inspectcode" --verbosity=WARN
    exit $?
fi

DIFF_ARGS=("HEAD")
if [[ "${1:-}" == "--staged" ]]; then
    DIFF_ARGS=("--cached")
fi

python3 - "${DIFF_ARGS[@]}" << 'EOF'
import os
import re
import subprocess
import sys

diff_args = sys.argv[1:]
repo_root = subprocess.check_output(["git", "rev-parse", "--show-toplevel"], text=True).strip().replace("\\", "/")

# 1. Block project files modified by UseLocalFramework
proj_diff = subprocess.check_output(
    ["git", "diff", *diff_args, "--", "osu.Game/osu.Game.csproj", "osu.Android.props", "osu.iOS.props", "osu.sln", "*.slnf"],
    text=True, encoding="utf-8", errors="replace"
)
if "g0v0-framework" in proj_diff:
    print("Project files contain local '../g0v0-framework' references (generated by UseLocalFramework). Please revert them before committing.", file=sys.stderr)
    sys.exit(1)

changed_files = [
    f.strip().replace("\\", "/")
    for f in subprocess.check_output(["git", "diff", *diff_args, "--name-only", "--diff-filter=ACMR", "--", "*.cs"], text=True).splitlines()
    if f.strip()
]
if not changed_files:
    sys.exit(0)

# 2. Parse git diff -U0 to collect newly added/modified line numbers and code
diff_output = subprocess.check_output(
    ["git", "diff", *diff_args, "-U0", "--diff-filter=ACMR", "--", "*.cs"],
    text=True, encoding="utf-8", errors="replace"
)

added_lines = {}
added_code = {}
current_file = None
current_ln = 0
hunk_re = re.compile(r"^@@ -\d+(?:,\d+)? \+(\d+)(?:,(\d+))? @@")

for line in diff_output.splitlines():
    if line.startswith("+++ b/"):
        current_file = line[6:].strip().replace("\\", "/")
        added_lines.setdefault(current_file, set())
        added_code.setdefault(current_file, {})
    elif line.startswith("@@ ") and current_file:
        m = hunk_re.match(line)
        if m:
            current_ln = int(m.group(1))
    elif line.startswith("+") and not line.startswith("+++") and current_file:
        added_lines[current_file].add(current_ln)
        added_code[current_file][current_ln] = line[1:]
        current_ln += 1

issues = []
const_re = re.compile(r"^\s*private\s+(?:const|static\s+readonly)\s+[\w<>\[\]\?,\s]+\s+([A-Za-z0-9_]+)\s*=")
field_re = re.compile(r"^\s*private\s+(?!const\b|static\b|readonly\s+struct\b|class\b|struct\b|enum\b|interface\b|record\b|delegate\b|event\b)(?:readonly\s+)?[\w<>\[\]\?,\s]+\s+(_[A-Za-z0-9_]+|[A-Z][A-Za-z0-9_]*)\s*[;=]")

# 3. Lightweight per-file CheckSanity + static checks on added lines
for rel_file in changed_files:
    if rel_file.endswith((".designer.cs", "AssemblyInfo.cs")) or not os.path.isfile(rel_file):
        continue

    with open(rel_file, "rb") as f:
        raw_text = f.read().decode("utf-8", errors="replace")

    stripped_crlf = raw_text.replace("\r\n", "")
    if "\n" in raw_text and "\n" in stripped_crlf:
        issues.append(f"  {rel_file}:1: [Sanity] Line endings must be CRLF (LF detected).")
    if "\r" in stripped_crlf:
        issues.append(f"  {rel_file}:1: [Sanity] Isolated CR character detected.")

    if "Licensed under the MIT License" in raw_text or "LICENSE file" in raw_text:
        issues.append(f"  {rel_file}:1: [Sanity] Copyright header must use British spelling 'Licence' / 'LICENCE'.")

    expected_type = os.path.splitext(os.path.basename(rel_file))[0].split(".")[0]
    if not re.search(rf"\b(class|struct|record|interface|enum)\s+{re.escape(expected_type)}\b", raw_text):
        issues.append(f"  {rel_file}:1: [Sanity] No matching type definition '{expected_type}' found in file.")

    for ln, code in added_code.get(rel_file, {}).items():
        if "\t" in code:
            issues.append(f"  {rel_file}:{ln}: [Sanity] Tab characters are not allowed.")
        if re.search(r"\s+$", code) and not re.match(r"^\s*///", code):
            issues.append(f"  {rel_file}:{ln}: [Sanity] Trailing whitespace is not allowed.")
        if re.match(r"^\s*#nullable\s+disable\b", code):
            issues.append(f"  {rel_file}:{ln}: [Style] '#nullable disable' is not allowed in newly added code.")

        m_const = const_re.search(code)
        if m_const and any(c.isupper() for c in m_const.group(1)):
            issues.append(f"  {rel_file}:{ln}: [Naming] Private const or static readonly field '{m_const.group(1)}' must use lower_snake_case.")

        m_field = field_re.search(code)
        if m_field:
            issues.append(f"  {rel_file}:{ln}: [Naming] Private field '{m_field.group(1)}' must use camelCase without an underscore prefix.")

# 4. Run single-project Roslyn code style analysis on affected projects
affected_projects = set()
for rel_file in changed_files:
    cur_dir = os.path.dirname(os.path.abspath(rel_file))
    while cur_dir.replace("\\", "/").startswith(repo_root):
        csprojs = [f for f in os.listdir(cur_dir) if f.endswith(".csproj")]
        if csprojs:
            affected_projects.add(os.path.join(cur_dir, csprojs[0]).replace("\\", "/"))
            break
        parent = os.path.dirname(cur_dir)
        if parent == cur_dir:
            break
        cur_dir = parent

diag_re = re.compile(r"^(?P<file>.+?)\((?P<line>\d+),(?P<col>\d+)\):\s+(?P<sev>error|warning)\s+(?P<code>[A-Z]+\d+):\s+(?P<msg>.+?)\s+\[")

for proj in sorted(affected_projects, key=len):
    proc = subprocess.run(
        [
            "dotnet", "build", proj,
            "-c", "Debug",
            "--no-restore",
            "--no-dependencies",
            "--no-incremental",
            "-p:EnforceCodeStyleInBuild=true",
            "-p:TreatWarningsAsErrors=false",
            "-p:CopyBuildOutputToOutputDirectory=false",
            "-p:CopyOutputSymbolsToOutputDirectory=false",
            "-v", "quiet",
            "-nologo"
        ],
        capture_output=True, text=True, encoding="utf-8", errors="replace"
    )
    output = (proc.stdout or "") + "\n" + (proc.stderr or "")
    for out_line in output.splitlines():
        m = diag_re.match(out_line.strip())
        if m:
            abs_file = m.group("file").replace("\\", "/")
            rel_path = abs_file[len(repo_root) + 1:] if abs_file.startswith(repo_root + "/") else abs_file
            line_num = int(m.group("line"))
            sev = m.group("sev").upper()
            code = m.group("code")
            msg = m.group("msg")

            if sev == "ERROR" or line_num in added_lines.get(rel_path, set()):
                issues.append(f"  {rel_path}:{line_num}: [{sev} {code}] {msg}")

unique_issues = list(dict.fromkeys(issues))
if unique_issues:
    print("InspectCode (lightweight) found issues in newly added content:", file=sys.stderr)
    for issue in unique_issues:
        print(issue, file=sys.stderr)
    sys.exit(1)
EOF
