using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace osu.Game.SourceGeneration
{
    [Generator]
    public sealed class RealmMapperGenerator : IIncrementalGenerator
    {
        private const string detach_attribute_fqn = "osu.Game.Database.GenerateRealmDetachAttribute";
        private const string copy_attribute_fqn = "osu.Game.Database.GenerateRealmCopyAttribute";

        private static readonly string[] ignored_attribute_names =
        {
            "Realms.IgnoredAttribute",
            "Realms.BacklinkAttribute",
            "System.Runtime.Serialization.IgnoreDataMemberAttribute"
        };

        private const string attributes_source = @"// <auto-generated/>
#nullable enable

using System;

namespace osu.Game.Database
{
    [AttributeUsage(AttributeTargets.Class, AllowMultiple = true, Inherited = false)]
    internal sealed class GenerateRealmDetachAttribute : Attribute
    {
        public Type TargetType { get; }

        public string[] IgnoredMembers { get; set; } = Array.Empty<string>();

        public string[] OptionalMembers { get; set; } = Array.Empty<string>();

        public GenerateRealmDetachAttribute(Type targetType)
        {
            TargetType = targetType;
        }
    }

    [AttributeUsage(AttributeTargets.Class, AllowMultiple = true, Inherited = false)]
    internal sealed class GenerateRealmCopyAttribute : Attribute
    {
        public Type TargetType { get; }

        public string[] IgnoredMembers { get; set; } = Array.Empty<string>();

        public GenerateRealmCopyAttribute(Type targetType)
        {
            TargetType = targetType;
        }
    }
}
";

        public void Initialize(IncrementalGeneratorInitializationContext context)
        {
            context.RegisterPostInitializationOutput(static ctx =>
                ctx.AddSource("RealmMapperAttributes.g.cs", attributes_source));

            var hostClasses = context.SyntaxProvider.CreateSyntaxProvider(
                predicate: static (node, _) => node is ClassDeclarationSyntax cds && cds.AttributeLists.Count > 0 && cds.Modifiers.Any(SyntaxKind.PartialKeyword),
                transform: static (ctx, _) => extractHostSpec(ctx))
                .Where(static spec => spec is not null);

            context.RegisterSourceOutput(hostClasses, static (spc, spec) =>
            {
                if (spec is null)
                    return;

                string source = emitHost(spec);
                spc.AddSource($"{spec.ClassName}.RealmMapper.g.cs", source);
            });
        }

        private static HostSpec? extractHostSpec(GeneratorSyntaxContext context)
        {
            if (context.Node is not ClassDeclarationSyntax cds)
                return null;

            if (context.SemanticModel.GetDeclaredSymbol(cds) is not INamedTypeSymbol hostSymbol)
                return null;

            var detachConfigs = new List<TypeConfig>();
            var copyConfigs = new List<TypeConfig>();

            foreach (var attr in hostSymbol.GetAttributes())
            {
                string? attrName = attr.AttributeClass?.ToDisplayString();
                if (attrName != detach_attribute_fqn && attrName != copy_attribute_fqn)
                    continue;

                if (attr.ConstructorArguments.Length != 1 || attr.ConstructorArguments[0].Value is not INamedTypeSymbol targetType)
                    continue;

                var ignored = extractStringArray(attr, "IgnoredMembers");
                var optional = extractStringArray(attr, "OptionalMembers");

                if (attrName == detach_attribute_fqn)
                    detachConfigs.Add(new TypeConfig(targetType, ignored, optional));
                else
                    copyConfigs.Add(new TypeConfig(targetType, ignored, ImmutableArray<string>.Empty));
            }

            if (detachConfigs.Count == 0 && copyConfigs.Count == 0)
                return null;

            var detachTypeSet = new HashSet<INamedTypeSymbol>(detachConfigs.Select(c => c.Type), SymbolEqualityComparer.Default);
            var copyTypeSet = new HashSet<INamedTypeSymbol>(copyConfigs.Select(c => c.Type), SymbolEqualityComparer.Default);

            // Map each detach type to its optional member names (and their target types) so back-references break cycles automatically.
            var optionalMembersByType = new Dictionary<INamedTypeSymbol, ImmutableArray<(string Name, INamedTypeSymbol? TargetType)>>(SymbolEqualityComparer.Default);
            foreach (var cfg in detachConfigs)
            {
                var builder = ImmutableArray.CreateBuilder<(string, INamedTypeSymbol?)>();
                var props = getModelProperties(cfg.Type);
                foreach (string opt in cfg.OptionalMembers)
                {
                    var prop = props.FirstOrDefault(p => p.Name == opt);
                    var target = prop?.Type.WithNullableAnnotation(NullableAnnotation.NotAnnotated) as INamedTypeSymbol;
                    builder.Add((opt, target));
                }

                optionalMembersByType[cfg.Type] = builder.ToImmutable();
            }

            var detachModels = detachConfigs
                .Select(cfg => buildDetachModel(cfg, detachTypeSet, optionalMembersByType))
                .ToImmutableArray();

            var copyModels = copyConfigs
                .Select(cfg => buildCopyModel(cfg, copyTypeSet))
                .ToImmutableArray();

            return new HostSpec(
                hostSymbol.ContainingNamespace.IsGlobalNamespace ? null : hostSymbol.ContainingNamespace.ToDisplayString(),
                hostSymbol.Name,
                hostSymbol.DeclaredAccessibility,
                hostSymbol.IsStatic,
                detachModels,
                copyModels);
        }

        private static ImmutableArray<string> extractStringArray(AttributeData attr, string namedArg)
        {
            foreach (var kv in attr.NamedArguments)
            {
                if (kv.Key == namedArg && !kv.Value.IsNull && kv.Value.Kind == TypedConstantKind.Array)
                {
                    return kv.Value.Values
                        .Where(v => v.Value is string)
                        .Select(v => (string)v.Value!)
                        .ToImmutableArray();
                }
            }

            return ImmutableArray<string>.Empty;
        }

        private static DetachModel buildDetachModel(
            TypeConfig cfg,
            HashSet<INamedTypeSymbol> detachTypeSet,
            Dictionary<INamedTypeSymbol, ImmutableArray<(string Name, INamedTypeSymbol? TargetType)>> optionalMembersByType)
        {
            var type = cfg.Type;
            var ignoredSet = new HashSet<string>(cfg.IgnoredMembers, StringComparer.Ordinal);
            var optionalSet = new HashSet<string>(cfg.OptionalMembers, StringComparer.Ordinal);

            bool hasPublicParameterlessCtor = type.InstanceConstructors.Any(c =>
                c.Parameters.Length == 0 && (c.DeclaredAccessibility == Accessibility.Public || c.DeclaredAccessibility == Accessibility.Internal));

            var properties = ImmutableArray.CreateBuilder<DetachProperty>();

            foreach (var prop in getModelProperties(type))
            {
                if (ignoredSet.Contains(prop.Name))
                    continue;

                bool isOptional = optionalSet.Contains(prop.Name);
                bool hasPublicSetter = prop.SetMethod?.DeclaredAccessibility == Accessibility.Public;

                if (hasPublicSetter)
                {
                    var nonNullType = prop.Type.WithNullableAnnotation(NullableAnnotation.NotAnnotated) as INamedTypeSymbol;
                    bool isMapped = nonNullType != null && detachTypeSet.Contains(nonNullType);

                    var childArgs = isMapped
                        ? buildChildOptionalArgs(type, nonNullType!, optionalMembersByType)
                        : ImmutableArray<string>.Empty;

                    properties.Add(new DetachProperty(
                        prop.Name,
                        DetachPropertyKind.ScalarOrMapped,
                        isMapped ? getMethodSuffix(nonNullType!) : null,
                        isOptional,
                        childArgs));
                }
                else if (tryGetIListElementType(prop.Type, out var elementType))
                {
                    var nonNullElem = elementType!.WithNullableAnnotation(NullableAnnotation.NotAnnotated) as INamedTypeSymbol;
                    bool isMappedElem = nonNullElem != null && detachTypeSet.Contains(nonNullElem);

                    var childArgs = isMappedElem
                        ? buildChildOptionalArgs(type, nonNullElem!, optionalMembersByType)
                        : ImmutableArray<string>.Empty;

                    properties.Add(new DetachProperty(
                        prop.Name,
                        isMappedElem ? DetachPropertyKind.MappedList : DetachPropertyKind.ValueList,
                        isMappedElem ? getMethodSuffix(nonNullElem!) : null,
                        isOptional,
                        childArgs));
                }
            }

            return new DetachModel(
                type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat),
                getMethodSuffix(type),
                hasPublicParameterlessCtor,
                cfg.OptionalMembers,
                properties.ToImmutable());
        }

        private static ImmutableArray<string> buildChildOptionalArgs(
            INamedTypeSymbol parentType,
            INamedTypeSymbol childType,
            Dictionary<INamedTypeSymbol, ImmutableArray<(string Name, INamedTypeSymbol? TargetType)>> optionalMembersByType)
        {
            if (!optionalMembersByType.TryGetValue(childType, out var childOptionals) || childOptionals.Length == 0)
                return ImmutableArray<string>.Empty;

            var args = ImmutableArray.CreateBuilder<string>(childOptionals.Length);
            foreach (var (name, targetType) in childOptionals)
            {
                // If the child's optional member points back to the parent type, disable it to break the cycle.
                // Otherwise (e.g. BeatmapInfo -> BeatmapSetInfo.Files), include it.
                bool value = !(targetType != null && SymbolEqualityComparer.Default.Equals(targetType, parentType));
                args.Add($"include{name}: {(value ? "true" : "false")}");
            }

            return args.ToImmutable();
        }

        private static CopyModel buildCopyModel(TypeConfig cfg, HashSet<INamedTypeSymbol> copyTypeSet)
        {
            var type = cfg.Type;
            var ignoredSet = new HashSet<string>(cfg.IgnoredMembers, StringComparer.Ordinal);
            var properties = ImmutableArray.CreateBuilder<CopyProperty>();

            foreach (var prop in getModelProperties(type))
            {
                if (ignoredSet.Contains(prop.Name))
                    continue;

                if (prop.SetMethod?.DeclaredAccessibility != Accessibility.Public)
                    continue;

                bool isPrimaryKey = hasAttribute(prop, "Realms.PrimaryKeyAttribute");
                var nonNullType = prop.Type.WithNullableAnnotation(NullableAnnotation.NotAnnotated) as INamedTypeSymbol;
                bool isMapped = nonNullType != null && copyTypeSet.Contains(nonNullType);

                properties.Add(new CopyProperty(
                    prop.Name,
                    prop.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat),
                    isPrimaryKey,
                    isMapped ? getMethodSuffix(nonNullType!) : null));
            }

            return new CopyModel(
                type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat),
                getMethodSuffix(type),
                properties.ToImmutable());
        }

        private static List<IPropertySymbol> getModelProperties(INamedTypeSymbol type)
        {
            var result = new List<IPropertySymbol>();
            var seen = new HashSet<string>(StringComparer.Ordinal);

            for (var current = type; current != null; current = current.BaseType)
            {
                string fqn = current.ToDisplayString();
                if (fqn == "Realms.RealmObjectBase" || fqn == "Realms.RealmObject" || fqn == "Realms.EmbeddedObject" || fqn == "System.Object")
                    break;

                foreach (var member in current.GetMembers())
                {
                    if (member is not IPropertySymbol prop)
                        continue;

                    if (prop.IsStatic || prop.IsIndexer || !prop.ExplicitInterfaceImplementations.IsEmpty)
                        continue;

                    if (prop.GetMethod?.DeclaredAccessibility != Accessibility.Public)
                        continue;

                    if (!seen.Add(prop.Name))
                        continue;

                    if (isIgnoredProperty(prop))
                        continue;

                    result.Add(prop);
                }
            }

            return result;
        }

        private static bool isIgnoredProperty(IPropertySymbol prop)
        {
            foreach (var attr in prop.GetAttributes())
            {
                string? name = attr.AttributeClass?.ToDisplayString();
                if (name != null && ignored_attribute_names.Contains(name))
                    return true;
            }

            return false;
        }

        private static bool hasAttribute(ISymbol symbol, string attributeFqn)
        {
            foreach (var attr in symbol.GetAttributes())
            {
                if (attr.AttributeClass?.ToDisplayString() == attributeFqn)
                    return true;
            }

            return false;
        }

        private static bool tryGetIListElementType(ITypeSymbol type, out ITypeSymbol? elementType)
        {
            if (type is INamedTypeSymbol named && named.IsGenericType
                && named.OriginalDefinition.ToDisplayString() == "System.Collections.Generic.IList<T>")
            {
                elementType = named.TypeArguments[0];
                return true;
            }

            elementType = null;
            return false;
        }

        private static string getMethodSuffix(INamedTypeSymbol type) => type.Name;

        private static string emitHost(HostSpec host)
        {
            var sb = new StringBuilder(4096);
            sb.AppendLine("// <auto-generated/>");
            sb.AppendLine("#nullable enable");
            sb.AppendLine("#pragma warning disable CS0618");
            sb.AppendLine();

            if (host.Namespace != null)
            {
                sb.Append("namespace ").AppendLine(host.Namespace);
                sb.AppendLine("{");
            }

            string indent = host.Namespace != null ? "    " : string.Empty;
            string accessibility = host.Accessibility switch
            {
                Accessibility.Public => "public",
                Accessibility.Internal => "internal",
                _ => "internal"
            };

            sb.Append(indent)
              .Append(accessibility)
              .Append(host.IsStatic ? " static partial class " : " partial class ")
              .AppendLine(host.ClassName);
            sb.Append(indent).AppendLine("{");

            string m = indent + "    ";

            // Generic Detach dispatch
            if (host.DetachModels.Length > 0)
            {
                sb.Append(m).AppendLine("private static T detachGenerated<T>(T item) where T : global::Realms.RealmObjectBase");
                sb.Append(m).AppendLine("{");
                sb.Append(m).AppendLine("    return item switch");
                sb.Append(m).AppendLine("    {");
                foreach (var model in host.DetachModels)
                {
                    string extraArgs = model.OptionalMembers.Length > 0
                        ? ", " + string.Join(", ", model.OptionalMembers.Select(o => $"include{o}: {(o == "Files" ? "false" : "true")}"))
                        : string.Empty;
                    sb.Append(m).Append("        ").Append(model.TypeFqn).Append(" s => (T)(object)detach_")
                      .Append(model.Suffix).Append("(s").Append(extraArgs).AppendLine("),");
                }

                sb.Append(m).AppendLine("        _ => throw new global::System.NotSupportedException($\"No generated Realm detach mapping exists for type '{item.GetType().FullName}'.\")");
                sb.Append(m).AppendLine("    };");
                sb.Append(m).AppendLine("}");
                sb.AppendLine();

                // Individual Detach methods + UnsafeAccessor constructors + partial hooks
                foreach (var model in host.DetachModels)
                {
                    if (!model.HasPublicParameterlessCtor)
                    {
                        sb.Append(m).AppendLine("[global::System.Runtime.CompilerServices.UnsafeAccessor(global::System.Runtime.CompilerServices.UnsafeAccessorKind.Constructor)]");
                        sb.Append(m).Append("private static extern ").Append(model.TypeFqn).Append(" create_").Append(model.Suffix).AppendLine("();");
                        sb.AppendLine();
                    }

                    sb.Append(m).Append("static partial void afterDetach_").Append(model.Suffix)
                      .Append("(").Append(model.TypeFqn).Append(" source, ").Append(model.TypeFqn).AppendLine(" destination);");
                    sb.AppendLine();

                    string paramList = model.OptionalMembers.Length > 0
                        ? ", " + string.Join(", ", model.OptionalMembers.Select(o => $"bool include{o}"))
                        : string.Empty;

                    sb.Append(m).Append("private static ").Append(model.TypeFqn).Append(" detach_").Append(model.Suffix)
                      .Append("(").Append(model.TypeFqn).Append(" source").Append(paramList).AppendLine(")");
                    sb.Append(m).AppendLine("{");
                    sb.Append(m).Append("    var destination = ")
                      .Append(model.HasPublicParameterlessCtor ? $"new {model.TypeFqn}()" : $"create_{model.Suffix}()")
                      .AppendLine(";");

                    foreach (var prop in model.Properties)
                    {
                        string innerIndent = prop.IsOptional ? m + "        " : m + "    ";
                        if (prop.IsOptional)
                        {
                            sb.Append(m).Append("    if (include").Append(prop.Name).AppendLine(")");
                            sb.Append(m).AppendLine("    {");
                        }

                        switch (prop.Kind)
                        {
                            case DetachPropertyKind.ScalarOrMapped:
                                if (prop.MappedSuffix != null)
                                {
                                    string args = prop.ChildOptionalArgs.Length > 0
                                        ? ", " + string.Join(", ", prop.ChildOptionalArgs)
                                        : string.Empty;
                                    sb.Append(innerIndent).Append("destination.").Append(prop.Name)
                                      .Append(" = source.").Append(prop.Name)
                                      .Append(" is null ? null! : detach_").Append(prop.MappedSuffix)
                                      .Append("(source.").Append(prop.Name).Append(args).AppendLine(");");
                                }
                                else
                                {
                                    sb.Append(innerIndent).Append("destination.").Append(prop.Name)
                                      .Append(" = source.").Append(prop.Name).AppendLine(";");
                                }
                                break;

                            case DetachPropertyKind.ValueList:
                                sb.Append(innerIndent).Append("if (source.").Append(prop.Name).AppendLine(" is not null)");
                                sb.Append(innerIndent).AppendLine("{");
                                sb.Append(innerIndent).Append("    destination.").Append(prop.Name).AppendLine(".Clear();");
                                sb.Append(innerIndent).Append("    foreach (var element in source.").Append(prop.Name).AppendLine(")");
                                sb.Append(innerIndent).Append("        destination.").Append(prop.Name).AppendLine(".Add(element);");
                                sb.Append(innerIndent).AppendLine("}");
                                break;

                            case DetachPropertyKind.MappedList:
                            {
                                string args = prop.ChildOptionalArgs.Length > 0
                                    ? ", " + string.Join(", ", prop.ChildOptionalArgs)
                                    : string.Empty;
                                sb.Append(innerIndent).Append("if (source.").Append(prop.Name).AppendLine(" is not null)");
                                sb.Append(innerIndent).AppendLine("{");
                                sb.Append(innerIndent).Append("    destination.").Append(prop.Name).AppendLine(".Clear();");
                                sb.Append(innerIndent).Append("    foreach (var element in source.").Append(prop.Name).AppendLine(")");
                                sb.Append(innerIndent).Append("        destination.").Append(prop.Name)
                                  .Append(".Add(element is null ? null! : detach_").Append(prop.MappedSuffix)
                                  .Append("(element").Append(args).AppendLine("));");
                                sb.Append(innerIndent).AppendLine("}");
                            }
                            break;
                        }

                        if (prop.IsOptional)
                            sb.Append(m).AppendLine("    }");
                    }

                    sb.Append(m).Append("    afterDetach_").Append(model.Suffix).AppendLine("(source, destination);");
                    sb.Append(m).AppendLine("    return destination;");
                    sb.Append(m).AppendLine("}");
                    sb.AppendLine();
                }
            }

            // CopyChangesToRealm methods
            foreach (var model in host.CopyModels)
            {
                sb.Append(m).Append("static partial void afterCopyToRealm_").Append(model.Suffix)
                  .Append("(").Append(model.TypeFqn).Append(" source, ").Append(model.TypeFqn).AppendLine(" destination);");
                sb.AppendLine();

                sb.Append(m).Append("private static void copyToRealm_").Append(model.Suffix)
                  .Append("(").Append(model.TypeFqn).Append(" source, ").Append(model.TypeFqn).AppendLine(" destination)");
                sb.Append(m).AppendLine("{");

                foreach (var prop in model.Properties)
                {
                    if (prop.IsPrimaryKey)
                    {
                        sb.Append(m).Append("    if (!global::System.Collections.Generic.EqualityComparer<").Append(prop.TypeFqn)
                          .Append(">.Default.Equals(destination.").Append(prop.Name).Append(", source.").Append(prop.Name).AppendLine("))");
                        sb.Append(m).Append("        destination.").Append(prop.Name).Append(" = source.").Append(prop.Name).AppendLine(";");
                    }
                    else if (prop.MappedSuffix != null)
                    {
                        sb.Append(m).Append("    if (source.").Append(prop.Name).Append(" is not null && destination.").Append(prop.Name).AppendLine(" is not null)");
                        sb.Append(m).Append("        copyToRealm_").Append(prop.MappedSuffix)
                          .Append("(source.").Append(prop.Name).Append(", destination.").Append(prop.Name).AppendLine(");");
                    }
                    else
                    {
                        sb.Append(m).Append("    destination.").Append(prop.Name)
                          .Append(" = source.").Append(prop.Name).AppendLine(";");
                    }
                }

                sb.Append(m).Append("    afterCopyToRealm_").Append(model.Suffix).AppendLine("(source, destination);");
                sb.Append(m).AppendLine("}");
                sb.AppendLine();
            }

            sb.Append(indent).AppendLine("}");
            if (host.Namespace != null)
                sb.AppendLine("}");

            return sb.ToString();
        }

        private sealed class TypeConfig
        {
            public INamedTypeSymbol Type { get; }
            public ImmutableArray<string> IgnoredMembers { get; }
            public ImmutableArray<string> OptionalMembers { get; }

            public TypeConfig(INamedTypeSymbol type, ImmutableArray<string> ignoredMembers, ImmutableArray<string> optionalMembers)
            {
                Type = type;
                IgnoredMembers = ignoredMembers;
                OptionalMembers = optionalMembers;
            }
        }

        private sealed class HostSpec
        {
            public string? Namespace { get; }
            public string ClassName { get; }
            public Accessibility Accessibility { get; }
            public bool IsStatic { get; }
            public ImmutableArray<DetachModel> DetachModels { get; }
            public ImmutableArray<CopyModel> CopyModels { get; }

            public HostSpec(
                string? ns,
                string className,
                Accessibility accessibility,
                bool isStatic,
                ImmutableArray<DetachModel> detachModels,
                ImmutableArray<CopyModel> copyModels)
            {
                Namespace = ns;
                ClassName = className;
                Accessibility = accessibility;
                IsStatic = isStatic;
                DetachModels = detachModels;
                CopyModels = copyModels;
            }
        }

        private sealed class DetachModel
        {
            public string TypeFqn { get; }
            public string Suffix { get; }
            public bool HasPublicParameterlessCtor { get; }
            public ImmutableArray<string> OptionalMembers { get; }
            public ImmutableArray<DetachProperty> Properties { get; }

            public DetachModel(
                string typeFqn,
                string suffix,
                bool hasPublicParameterlessCtor,
                ImmutableArray<string> optionalMembers,
                ImmutableArray<DetachProperty> properties)
            {
                TypeFqn = typeFqn;
                Suffix = suffix;
                HasPublicParameterlessCtor = hasPublicParameterlessCtor;
                OptionalMembers = optionalMembers;
                Properties = properties;
            }
        }

        private enum DetachPropertyKind
        {
            ScalarOrMapped,
            ValueList,
            MappedList
        }

        private sealed class DetachProperty
        {
            public string Name { get; }
            public DetachPropertyKind Kind { get; }
            public string? MappedSuffix { get; }
            public bool IsOptional { get; }
            public ImmutableArray<string> ChildOptionalArgs { get; }

            public DetachProperty(
                string name,
                DetachPropertyKind kind,
                string? mappedSuffix,
                bool isOptional,
                ImmutableArray<string> childOptionalArgs)
            {
                Name = name;
                Kind = kind;
                MappedSuffix = mappedSuffix;
                IsOptional = isOptional;
                ChildOptionalArgs = childOptionalArgs;
            }
        }

        private sealed class CopyModel
        {
            public string TypeFqn { get; }
            public string Suffix { get; }
            public ImmutableArray<CopyProperty> Properties { get; }

            public CopyModel(string typeFqn, string suffix, ImmutableArray<CopyProperty> properties)
            {
                TypeFqn = typeFqn;
                Suffix = suffix;
                Properties = properties;
            }
        }

        private sealed class CopyProperty
        {
            public string Name { get; }
            public string TypeFqn { get; }
            public bool IsPrimaryKey { get; }
            public string? MappedSuffix { get; }

            public CopyProperty(string name, string typeFqn, bool isPrimaryKey, string? mappedSuffix)
            {
                Name = name;
                TypeFqn = typeFqn;
                IsPrimaryKey = isPrimaryKey;
                MappedSuffix = mappedSuffix;
            }
        }
    }
}
