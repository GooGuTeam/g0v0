param (
    [switch]$Staged,
    [switch]$Full
)

$ErrorActionPreference = "Stop"
[Console]::OutputEncoding = [System.Text.Encoding]::UTF8
$OutputEncoding = [System.Text.Encoding]::UTF8

$repoRoot = (git rev-parse --show-toplevel).Trim().Replace("\", "/")
Set-Location $repoRoot

if ($Full) {
    dotnet tool restore
    # clean is required to ensure all code style errors are (re-)raised by compiler
    dotnet clean ./osu.Desktop.slnf --verbosity=q
    dotnet build -c Debug -warnaserror osu.Desktop.slnf -p:EnforceCodeStyleInBuild=true
    ./CheckSanity.ps1
    dotnet jb inspectcode "osu.Desktop.slnf" --no-build --format=Text --stdout --caches-home="inspectcode" --verbosity=WARN
    exit $LASTEXITCODE
}

$diffArgs = @(if ($Staged) { "--cached" } else { "HEAD" })

# 1. Block project files modified by UseLocalFramework
$projectFilesDiff = git diff @diffArgs -- "osu.Game/osu.Game.csproj" "osu.Android.props" "osu.iOS.props" "osu.sln" "*.slnf"
if ($projectFilesDiff -match "g0v0-framework") {
    [Console]::Error.WriteLine("Project files contain local '../g0v0-framework' references (generated by UseLocalFramework). Please revert them before committing.")
    exit 1
}

$changedFiles = @(git diff @diffArgs --name-only --diff-filter=ACMR -- "*.cs")
if ($changedFiles.Count -eq 0) {
    exit 0
}

# 2. Parse git diff -U0 to collect newly added/modified line numbers and code
$diffOutput = git diff @diffArgs -U0 --diff-filter=ACMR -- "*.cs"
$addedLines = @{}
$addedCode = @{}
$currentFile = $null
$currentNewLine = 0

foreach ($line in $diffOutput) {
    if ($line.StartsWith("+++ b/")) {
        $currentFile = $line.Substring(6).Trim().Replace("\", "/")
        if (-not $addedLines.ContainsKey($currentFile)) {
            $addedLines[$currentFile] = [System.Collections.Generic.HashSet[int]]::new()
            $addedCode[$currentFile] = @{}
        }
    }
    elseif ($line.StartsWith("@@ ") -and $null -ne $currentFile) {
        if ($line -match "^@@ -\d+(?:,\d+)? \+(\d+)(?:,(\d+))? @@") {
            $currentNewLine = [int]$Matches[1]
        }
    }
    elseif ($line.StartsWith("+") -and -not $line.StartsWith("+++") -and $null -ne $currentFile) {
        [void]$addedLines[$currentFile].Add($currentNewLine)
        $addedCode[$currentFile][$currentNewLine] = $line.Substring(1)
        $currentNewLine++
    }
}

$issues = [System.Collections.Generic.List[string]]::new()

# 3. Lightweight per-file CheckSanity + static checks on added lines
foreach ($relFile in $changedFiles) {
    $relFile = $relFile.Replace("\", "/")
    if ($relFile -match "(\.designer\.cs|AssemblyInfo\.cs)$" -or -not (Test-Path $relFile)) {
        continue
    }

    $rawBytes = [System.IO.File]::ReadAllBytes((Join-Path $repoRoot $relFile))
    $rawText = [System.Text.Encoding]::UTF8.GetString($rawBytes)

    if ($rawText.Contains("`n") -and ($rawText -replace "`r`n", "").Contains("`n")) {
        $issues.Add("  ${relFile}:1: [Sanity] Line endings must be CRLF (LF detected).")
    }
    if (($rawText -replace "`r`n", "").Contains("`r")) {
        $issues.Add("  ${relFile}:1: [Sanity] Isolated CR character detected.")
    }

    if ($rawText -match "Licensed under the MIT License" -or $rawText -match "LICENSE file") {
        $issues.Add("  ${relFile}:1: [Sanity] Copyright header must use British spelling 'Licence' / 'LICENCE'.")
    }

    $expectedType = [System.IO.Path]::GetFileNameWithoutExtension($relFile).Split('.')[0]
    if ($rawText -notmatch "\b(class|struct|record|interface|enum)\s+$expectedType\b") {
        $issues.Add("  ${relFile}:1: [Sanity] No matching type definition '$expectedType' found in file.")
    }

    if ($addedCode.ContainsKey($relFile)) {
        foreach ($kv in $addedCode[$relFile].GetEnumerator()) {
            $ln = $kv.Key
            $code = $kv.Value

            if ($code.Contains("`t")) {
                $issues.Add("  ${relFile}:${ln}: [Sanity] Tab characters are not allowed.")
            }
            if ($code -match "\s+$" -and $code -notmatch "^\s*///") {
                $issues.Add("  ${relFile}:${ln}: [Sanity] Trailing whitespace is not allowed.")
            }
            if ($code -match "^\s*#nullable\s+disable\b") {
                $issues.Add("  ${relFile}:${ln}: [Style] '#nullable disable' is not allowed in newly added code.")
            }
            if ($code -match "^\s*private\s+(?:const|static\s+readonly)\s+[\w<>\[\]\?,\s]+\s+([A-Za-z0-9_]+)\s*=") {
                $fieldName = $Matches[1]
                if ($fieldName -cmatch "[A-Z]") {
                    $issues.Add("  ${relFile}:${ln}: [Naming] Private const or static readonly field '$fieldName' must use lower_snake_case.")
                }
            }
            if ($code -match "^\s*private\s+(?!const\b|static\b|readonly\s+struct\b|class\b|struct\b|enum\b|interface\b|record\b|delegate\b|event\b)(?:readonly\s+)?[\w<>\[\]\?,\s]+\s+(_[A-Za-z0-9_]+|[A-Z][A-Za-z0-9_]*)\s*[;=]") {
                $fieldName = $Matches[1]
                $issues.Add("  ${relFile}:${ln}: [Naming] Private field '$fieldName' must use camelCase without an underscore prefix.")
            }
        }
    }
}

# 4. Run single-project Roslyn code style analysis on affected projects
$affectedProjects = [System.Collections.Generic.HashSet[string]]::new()
foreach ($relFile in $changedFiles) {
    $dir = Split-Path (Join-Path $repoRoot $relFile) -Parent
    while ($dir -and $dir.Replace("\", "/").StartsWith($repoRoot)) {
        $csproj = Get-ChildItem -Path $dir -Filter "*.csproj" -File -ErrorAction SilentlyContinue | Select-Object -First 1
        if ($csproj) {
            [void]$affectedProjects.Add($csproj.FullName.Replace("\", "/"))
            break
        }
        $dir = Split-Path $dir -Parent
    }
}

$sortedProjects = $affectedProjects | Sort-Object { $_.Length }
$diagRegex = [regex]"^(?<file>.+?)\((?<line>\d+),(?<col>\d+)\):\s+(?<severity>error|warning)\s+(?<code>[A-Z]+\d+):\s+(?<msg>.+?)\s+\["

foreach ($proj in $sortedProjects) {
    $buildOutput = dotnet build $proj `
        -c Debug `
        --no-restore `
        --no-dependencies `
        --no-incremental `
        -p:EnforceCodeStyleInBuild=true `
        -p:TreatWarningsAsErrors=false `
        -p:CopyBuildOutputToOutputDirectory=false `
        -p:CopyOutputSymbolsToOutputDirectory=false `
        -v quiet `
        -nologo 2>&1

    foreach ($outLine in $buildOutput) {
        $text = $outLine.ToString().Trim()
        $m = $diagRegex.Match($text)
        if ($m.Success) {
            $absFile = $m.Groups["file"].Value.Replace("\", "/")
            $relPath = if ($absFile.StartsWith("$repoRoot/")) { $absFile.Substring($repoRoot.Length + 1) } else { $absFile }
            $lineNum = [int]$m.Groups["line"].Value
            $sev = $m.Groups["severity"].Value.ToUpper()
            $code = $m.Groups["code"].Value
            $msg = $m.Groups["msg"].Value

            if ($sev -eq "ERROR" -or ($addedLines.ContainsKey($relPath) -and $addedLines[$relPath].Contains($lineNum))) {
                $issues.Add("  ${relPath}:${lineNum}: [$sev $code] $msg")
            }
        }
    }
}

$uniqueIssues = @($issues | Select-Object -Unique)
if ($uniqueIssues.Count -gt 0) {
    [Console]::Error.WriteLine("InspectCode (lightweight) found issues in newly added content:")
    foreach ($issue in $uniqueIssues) {
        [Console]::Error.WriteLine($issue)
    }
    exit 1
}
